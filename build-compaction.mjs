// Regenerates only the preset overlays from the exact installed DSH declarations.
// Run with Electron as Node when the input is inside app.asar.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [root, flag] = process.argv.slice(2);
if (!root || (flag !== undefined && flag !== '--check')) {
  throw new Error('Usage: build-compaction.mjs <DSH root> [--check]');
}
const require = createRequire(join(resolve(root), 'package.json'));
const yaml = require('js-yaml');
const { entryListSchema } = await import(pathToFileURL(require.resolve('@deepseek-ai/cordis-plugin-include')));
const { getDshRuntimeVersion } = await import(pathToFileURL(require.resolve('@deepseek-ai/dsh-app-boot')));
assert.equal(getDshRuntimeVersion(), '0.2.2-rc.5');
const path = id => join(resolve(root), 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', `${id}.patch.yml`);
const inputs = ['standard', 'ptc', 'cordis', 'minimal'].map(id => [id, path(id)]);
const output = [{ insert: [{ id: 'harness-enhanced', name: '@local/dsh-harness-enhanced' }] }];
for (const [id, path] of inputs) {
  const source = yaml.load(await readFile(path, 'utf8'), { schema: entryListSchema });
  const matches = source.flatMap(patch => patch.insert ?? []).filter(row => row.id === `preset-${id}`);
  assert.equal(matches.length, 1);
  const [entry] = matches;
  assert.equal(entry.name, '@deepseek-ai/dsh-agent-preset');
  assert.equal(entry.config.id, id);
  const groups = entry.config.plugins.filter(row => row.id === 'compaction');
  assert.equal(groups.length, 1);
  const [group] = groups;
  assert.equal(group.name, 'cordis:group');
  assert.equal(group.group, true);
  assert.equal(group.isolate.compaction, true);
  const backends = group.config.filter(row => row.id === 'compaction-basic');
  assert.equal(backends.length, 1);
  assert.equal(backends[0].name, '@deepseek-ai/dsh-compaction-basic');
  backends[0].name = '@local/dsh-harness-enhanced/compaction';
  output.push({ id: entry.id, name: entry.name, config: entry.config });
}
const patch = '# Generated by build-compaction.mjs from the installed rc.5 presets.\n'
  + yaml.dump(output, { schema: entryListSchema, lineWidth: -1, noRefs: true });
const destination = new URL('./cordis.patch.yml', import.meta.url);
if (flag === '--check') assert.equal(await readFile(destination, 'utf8'), patch);
else await writeFile(destination, patch, 'utf8');
