import { readFile, writeFile } from 'node:fs/promises';
import { createExpansion } from './expansion.js';

const read = name => readFile(new URL(`./${name}`, import.meta.url), 'utf8');
let template = await read('client.template.js');
function inline(marker, source) {
  marker = `    /* __${marker}__ */`;
  if (template.split(marker).length !== 2) throw new Error(`Expected exactly one ${marker}`);
  template = template.replace(marker, () => source.split('\n').map(line => line && `    ${line}`).join('\n'));
}
inline('EXPANSION_CONTROLLER', createExpansion.toString());
async function inlineModules(marker, names) {
  const modules = await Promise.all(names.map(read));
  inline(marker, modules.map(source => source
    .replace(/^import [^\n]+;\r?\n/gm, '')
    .replace(/^export (?=(?:const|function|async function) )/gm, '')
    .trim()).join('\n\n'));
}
await inlineModules('FAILED_MESSAGE_UI', ['failure-proof.js', 'restore-draft.js', 'failed-message-ui.js']);
await inlineModules('DIRECTORY_LINK_CLIENT', ['local-link-path.js', 'directory-link-client.js']);
const client = `// Generated by node build.mjs. Edit client.template.js or its source modules instead.\n${template}`;
const out = new URL('./client.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(out, 'utf8') !== client) throw new Error('client.js is out of date; run node build.mjs');
} else {
  await writeFile(out, client, 'utf8');
}
